"""Generate IEEE LaTeX result rows from the comparison artifact."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COMPARISON = ROOT / "reports" / "results" / "comparison.json"
OUTPUT = ROOT / "reports" / "ieee" / "generated_tables.tex"


def tex_escape(value: str) -> str:
    return value.replace("_", r"\_").replace("%", r"\%").replace("&", r"\&")


def make_rows() -> list[str]:
    if not COMPARISON.is_file():
        return [r"No new evaluation runs & PENDING & PENDING & PENDING & PENDING \\"]
    data = json.loads(COMPARISON.read_text(encoding="utf-8"))
    rows: list[str] = []
    for run in data.get("runs", []):
        metrics = run.get("metrics") or {}
        values = [
            tex_escape(str(run.get("run_id", "unknown"))),
            str(run.get("status", "PENDING")),
            _format(metrics.get("accuracy")),
            _format(metrics.get("macro_f1")),
            _format(metrics.get("neutral_recall")),
        ]
        rows.append(" & ".join(values) + r" \\")
    return rows or [r"No new evaluation runs & PENDING & PENDING & PENDING & PENDING \\"]


def _format(value: object) -> str:
    return "PENDING" if value is None else f"{float(value):.4f}"


def main() -> None:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "% Generated by reports/make_tables.py; do not edit by hand.",
        r"\begin{tabular}{lrrrr}",
        r"\hline",
        r"Run & Status & Accuracy & Macro-F1 & Neutral recall \\",
        r"\hline",
        *make_rows(),
        r"\hline",
        r"\end{tabular}",
    ]
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    try:
        display_path = OUTPUT.relative_to(ROOT)
    except ValueError:
        display_path = OUTPUT
    print(f"Wrote {display_path}")


if __name__ == "__main__":
    main()
